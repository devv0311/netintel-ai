import type { EvaluationReport, MetricResult } from "@/lib/evaluation/types";

const pct = (value: number | null): string =>
  value === null ? "—" : `${(value * 100).toFixed(1)}%`;

const frac = (m: MetricResult): string =>
  m.numerator === null || m.denominator === null
    ? "—"
    : `${round(m.numerator)} / ${round(m.denominator)}`;

const round = (n: number): string => (Number.isInteger(n) ? String(n) : n.toFixed(3));

/**
 * Renders the human-readable half of the evaluation output.
 *
 * Every metric prints its definition, numerator, denominator, ground
 * truth source and limitations — the report is meant to be arguable
 * with, not just read. A metric with no threshold prints "none defined"
 * rather than an implied pass.
 */
export function renderMarkdown(report: EvaluationReport): string {
  const lines: string[] = [];
  const { meta, summary } = report;

  lines.push("# Evaluation Summary — Operation DarkNet Delhi");
  lines.push("");
  lines.push("<!-- GENERATED by scripts/evaluate.ts. Do not edit by hand. -->");
  lines.push("");
  lines.push(`**Run id:** \`${meta.runId}\`  `);
  lines.push(`**Completed:** ${meta.completedAt}  `);
  lines.push(`**Corpus:** ${meta.corpusName} v${meta.corpusVersion} (seed ${meta.corpusSeed})  `);
  lines.push(`**Ground truth:** \`${meta.groundTruthPath}\`  `);
  lines.push(`**Commit:** \`${meta.gitCommit ?? "unknown"}\`  `);
  lines.push(`**Node:** ${meta.nodeVersion}`);
  lines.push("");
  lines.push(
    `${summary.measured} metrics measured · ${summary.notImplementableYet} not implementable yet · ` +
      `${summary.withThreshold} with a project-defined threshold (${summary.thresholdsPassed} passed, ${summary.thresholdsFailed} failed).`,
  );
  lines.push("");
  lines.push(
    "> Thresholds are only shown where the project already fixed one. Everything else is measured and left un-judged — `docs/evaluation/evaluation-spec.md` §3 requires a threshold to be set with a rationale before it is used, and this harness does not invent them.",
  );
  lines.push("");

  if (report.errors.length > 0) {
    lines.push("## Errors");
    lines.push("");
    for (const error of report.errors) lines.push(`- ${error}`);
    lines.push("");
  }

  lines.push("## Results at a glance");
  lines.push("");
  lines.push("| Metric | Value | Count | Threshold | Verdict |");
  lines.push("|---|---|---|---|---|");
  for (const m of report.metrics) {
    if (m.status === "not_implementable_yet") {
      lines.push(`| ${m.name} | — | — | — | \`NOT IMPLEMENTABLE YET\` |`);
      continue;
    }
    const threshold = m.threshold ? `${m.threshold.comparison} ${pct(m.threshold.value)}` : "none defined";
    const verdict = m.passed === null ? "measured, un-judged" : m.passed ? "**PASS**" : "**FAIL**";
    lines.push(`| ${m.name} | ${pct(m.value)} | ${frac(m)} | ${threshold} | ${verdict} |`);
  }
  lines.push("");

  lines.push("## Pipeline run");
  lines.push("");
  lines.push("| Stage | Duration | Detail |");
  lines.push("|---|---|---|");
  for (const stage of meta.pipelineStages) {
    lines.push(`| ${stage.stage} | ${(stage.ms / 1000).toFixed(1)}s | ${stage.detail} |`);
  }
  lines.push("");

  lines.push("## Metric detail");
  lines.push("");
  for (const m of report.metrics) {
    lines.push(`### ${m.name}`);
    lines.push("");
    lines.push(`- **id**: \`${m.id}\``);
    lines.push(`- **category**: ${m.category}`);
    lines.push(`- **status**: \`${m.status === "measured" ? "MEASURED" : "NOT IMPLEMENTABLE YET"}\``);
    lines.push(`- **definition**: ${m.definition}`);
    lines.push(`- **numerator**: ${m.numeratorDefinition}${m.numerator === null ? "" : ` — ${round(m.numerator)}`}`);
    lines.push(`- **denominator**: ${m.denominatorDefinition}${m.denominator === null ? "" : ` — ${round(m.denominator)}`}`);
    lines.push(`- **value**: ${pct(m.value)}`);
    lines.push(`- **ground truth**: ${m.groundTruthSource}`);
    lines.push(`- **system input**: ${m.systemInput}`);
    lines.push(
      `- **threshold**: ${m.threshold ? `${m.threshold.comparison} ${m.threshold.value} — ${m.threshold.source}` : "none defined by the project; this harness does not invent one"}`,
    );
    lines.push("- **known limitations**:");
    for (const limitation of m.limitations) lines.push(`  - ${limitation}`);
    if (m.details) {
      lines.push("");
      lines.push("<details><summary>Breakdown</summary>");
      lines.push("");
      lines.push("```json");
      lines.push(JSON.stringify(m.details, null, 2));
      lines.push("```");
      lines.push("");
      lines.push("</details>");
    }
    lines.push("");
  }
  return lines.join("\n") + "\n";
}
